def write(path, content, check=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, str):
        content = (content.rstrip() + '\n').encode('utf-8')
        if path.exists():
            old = path.read_bytes()
            assert old.count(b'\r\n') in (0, old.count(b'\n')), path
            if b'\r\n' in old:
                content = content.replace(b'\n', b'\r\n')
    if check:
        assert path.read_bytes() == content, f'Stale generated file: {path}'
    else:
        path.write_bytes(content)


def read_glb(path):
    # Inspect the complete JSON scene before touching the binary payload.
    with path.open('rb') as f:
        magic, version, length = struct.unpack('<4sII', f.read(12))
        assert magic == b'glTF' and version == 2 and length == path.stat().st_size
        size, kind = struct.unpack('<I4s', f.read(8))
        assert kind == b'JSON'
        g = json.loads(f.read(size))
        assert not g.get('extensionsRequired'), 'Unsupported required GLB extension'
        size, kind = struct.unpack('<I4s', f.read(8))
        assert kind == b'BIN\x00'
        blob = f.read(size)
        assert f.tell() == length

    def accessor(index):
        a = g['accessors'][index]
        assert 'sparse' not in a
        view = g['bufferViews'][a['bufferView']]
        assert view['buffer'] == 0
        dtype = np.dtype({5120: '<i1', 5121: '<u1', 5122: '<i2', 5123: '<u2',
                          5125: '<u4', 5126: '<f4'}[a['componentType']])
        columns = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4}[a['type']]
        stride = view.get('byteStride', columns * dtype.itemsize)
        offset = view.get('byteOffset', 0) + a.get('byteOffset', 0)
        assert offset + (a['count'] - 1) * stride + columns * dtype.itemsize <= view.get('byteOffset', 0) + view['byteLength']
        out = np.ndarray((a['count'], columns), dtype=dtype, buffer=blob,
                         offset=offset, strides=(stride, dtype.itemsize)).astype(float)
        if a.get('normalized') and dtype.kind != 'f':
            out /= np.iinfo(dtype).max
            if dtype.kind == 'i':
                out = np.maximum(out, -1)
        return out

    primitives = []

    def visit(index, parent):
        node = g['nodes'][index]
        if 'matrix' in node:
            matrix = np.asarray(node['matrix']).reshape((4, 4), order='F')
        else:
            x, y, z, w = node.get('rotation', [0, 0, 0, 1])
            rotation = np.array([[1-2*(y*y+z*z), 2*(x*y-z*w), 2*(x*z+y*w)],
                                 [2*(x*y+z*w), 1-2*(x*x+z*z), 2*(y*z-x*w)],
                                 [2*(x*z-y*w), 2*(y*z+x*w), 1-2*(x*x+y*y)]])
            matrix = np.eye(4)
            matrix[:3, :3] = rotation @ np.diag(node.get('scale', [1, 1, 1]))
            matrix[:3, 3] = node.get('translation', [0, 0, 0])
        transform = parent @ matrix
        if 'mesh' in node:
            for primitive in g['meshes'][node['mesh']]['primitives']:
                # This source explicitly declares TRIANGLES. Never reinterpret
                # line/point/strip primitives as triangles.
                assert primitive.get('mode', 4) == 4
                assert set(primitive['attributes']) == {'POSITION', 'NORMAL', 'TEXCOORD_0'}
                positions = accessor(primitive['attributes']['POSITION'])
                positions = (np.c_[positions, np.ones(len(positions))] @ transform.T)[:, :3]
                uv = accessor(primitive['attributes']['TEXCOORD_0'])
                indices = accessor(primitive['indices']).astype(np.int32).reshape(-1, 3)
                assert indices.min() >= 0 and indices.max() < len(positions)
                material = g['materials'][primitive['material']]
                assert material.get('alphaMode', 'OPAQUE') == 'OPAQUE'
                pbr = material['pbrMetallicRoughness']
                assert pbr.get('baseColorFactor', [1, 1, 1, 1]) == [1, 1, 1, 1]
                texture = g['textures'][pbr['baseColorTexture']['index']]
                assert pbr['baseColorTexture'].get('texCoord', 0) == 0
                assert g['samplers'][texture['sampler']]['wrapS'] == 33071
                assert g['samplers'][texture['sampler']]['wrapT'] == 33071
                image = g['images'][texture['source']]
                view = g['bufferViews'][image['bufferView']]
                start = view.get('byteOffset', 0)
                pixels = np.asarray(Image.open(io.BytesIO(blob[start:start+view['byteLength']])).convert('RGB'))
                primitives.append((positions, uv, indices, pixels))
        for child in node.get('children', []):
            visit(child, transform)

    for index in g['scenes'][g.get('scene', 0)]['nodes']:
        visit(index, np.eye(4))
    assert len(primitives) == 1, 'This converter is scoped to the supplied single-material box'
    metadata = dict(source=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                    format='glTF 2.0 GLB, little-endian', bytes=length,
                    vertices=sum(len(p[0]) for p in primitives),
                    triangles=sum(len(p[2]) for p in primitives), primitive_modes=['TRIANGLES'],
                    scene=g['scenes'][g.get('scene', 0)], nodes=g['nodes'],
                    materials=g['materials'], texture_dimensions=list(primitives[0][3].shape[:2][::-1]),
                    excluded_geometry=[], transforms_applied=True)
    return primitives[0], metadata


def lab(rgb):
    rgb = np.asarray(rgb, dtype=float) / 255
    linear = np.where(rgb <= .04045, rgb / 12.92, ((rgb + .055) / 1.055) ** 2.4)
    xyz = linear @ np.array([[.4124564, .3575761, .1804375],
                             [.2126729, .7151522, .0721750],
                             [.0193339, .1191920, .9503041]]).T
    xyz /= [.95047, 1, 1.08883]
    f = np.where(xyz > (6/29)**3, np.cbrt(xyz), xyz/(3*(6/29)**2)+4/29)
    return np.stack((116*f[..., 1]-16, 500*(f[..., 0]-f[..., 1]),
                     200*(f[..., 1]-f[..., 2])), axis=-1)


def palette(refresh=False):
    path = DOCS / 'palette.json'
    if path.exists() and not refresh:
        return json.loads(path.read_bytes())
    colors = ['white', 'orange', 'magenta', 'light_blue', 'yellow', 'lime', 'pink',
              'gray', 'light_gray', 'cyan', 'purple', 'blue', 'brown', 'green', 'red', 'black']
    resources = []
    for color in colors:
        texture_color = 'silver' if color == 'light_gray' else color
        resources += [(f'{color}_concrete', f'concrete_{texture_color}'),
                      (f'{color}_terracotta', f'hardened_clay_stained_{texture_color}'),
                      (f'{color}_wool', f'wool_colored_{texture_color}')]
    resources += [('hardened_clay', 'hardened_clay')]
    catalog = json.load(urllib.request.urlopen(UPSTREAM+'metadata/vanilladata_modules/mojang-blocks.json', timeout=30))
    names = {b['name'] for b in catalog['data_items']}

    def fetch(item):
        block, texture = item
        name = 'minecraft:' + block
        assert name in names, name
        data = urllib.request.urlopen(UPSTREAM+f'resource_pack/textures/blocks/{texture}.png', timeout=30).read()
        pixels = np.asarray(Image.open(io.BytesIO(data)).convert('RGB'))
        return dict(block=name, rgb=np.round(pixels.mean(axis=(0, 1)), 4).tolist(),
                    texture=texture+'.png', texture_sha256=hashlib.sha256(data).hexdigest())
    with ThreadPoolExecutor(max_workers=8) as pool:
        entries = sorted(pool.map(fetch, resources), key=lambda e:e['block'])
    data = dict(source=UPSTREAM, method='Nearest Euclidean CIELAB (D65, sRGB), no dithering; mean official block texture RGB', entries=entries)
    write(path, json.dumps(data, indent=2))
    return data


def voxelize(primitive, metadata, colors):
    positions, uv, indices, texture = primitive
    lo, hi = positions.min(axis=0), positions.max(axis=0)
    scale = 359 / (hi[1] - lo[1])
    # +model Z is the photographed front. Invert both X and depth to keep its
    # lettering readable from the observation point in caret-local coordinates.
    points = positions * [-1, 1, -1] * scale
    points[:, 0] -= (points[:, 0].min() + points[:, 0].max()) / 2
    points[:, 1] += 1 - points[:, 1].min()
    points[:, 2] += 32 - points[:, 2].min()
    all_points, all_uv, distances = [], [], []
    grids = {}
    for triangle in indices:
        p, t = points[triangle], uv[triangle]
        # A barycentric mesh at <=1/3 block along the longest edge samples the
        # faces themselves, including every edge. No vertex-only conversion.
        steps = max(1, math.ceil(max(np.linalg.norm(p[a]-p[b]) for a,b in ((0,1),(0,2),(1,2))) * 3))
        if steps not in grids:
            weights = np.array([(i/steps, j/steps) for i in range(steps+1) for j in range(steps+1-i)])
            grids[steps] = np.c_[1-weights.sum(axis=1), weights]
        weights = grids[steps]
        samples = weights @ p
        cells = np.floor(samples+.5).astype(np.int16)
        all_points.append(cells)
        all_uv.append((weights @ t).astype(np.float32))
        distances.append(((samples-cells)**2).sum(axis=1).astype(np.float32))
    cells, texcoords, distances = np.concatenate(all_points), np.concatenate(all_uv), np.concatenate(distances)
    lower, upper = cells.min(axis=0), cells.max(axis=0)
    sizes = upper-lower+1
    keys = np.ravel_multi_index((cells-lower).T, sizes)
    # Nearest sampled surface wins; stable sample index breaks exact ties.
    order = np.lexsort((np.arange(len(keys)), distances, keys))
    selected = order[np.r_[True, keys[order][1:] != keys[order][:-1]]]
    cells, texcoords = cells[selected], texcoords[selected]
    h, w = texture.shape[:2]
    coords = np.clip(texcoords * [w, h] - .5, [0, 0], [w-1, h-1])
    x, y = np.floor(coords).astype(int).T
    dx, dy = (coords-np.floor(coords)).T
    x1, y1 = np.minimum(x+1,w-1), np.minimum(y+1,h-1)
    rgb = (texture[y,x]*(1-dx)[:,None]*(1-dy)[:,None] + texture[y,x1]*dx[:,None]*(1-dy)[:,None]
           + texture[y1,x]*(1-dx)[:,None]*dy[:,None] + texture[y1,x1]*dx[:,None]*dy[:,None])
    entries = colors['entries']
    references = lab([e['rgb'] for e in entries])
    ids = np.empty(len(cells), np.int16)
    for start in range(0,len(cells),10000):
        value = lab(rgb[start:start+10000])
        ids[start:start+10000] = ((value[:,None,:]-references[None,:,:])**2).sum(axis=2).argmin(axis=1)
    scene = {tuple(map(int,p)):entries[int(i)]['block'] for p,i in zip(cells,ids)}
    metadata.update(source_bounds=[lo.tolist(), hi.tolist()], uniform_scale=scale,
                    axis_mapping='caret left=-model X, up=model Y, forward=-model Z; front is +model Z',
                    surface_sampling='Barycentric triangle sampling, at least three samples per longest-edge block; nearest-surface sample wins, stable index ties',
                    sample_count=len(keys), bounds=[lower.tolist(),upper.tolist()],
                    dimensions=dict(width=int(sizes[0]),height=int(sizes[1]),depth=int(sizes[2])),
                    non_air_blocks=len(scene), air_cells=0, interior='Unfilled, omitted cells use -1; no exterior air clearing',
                    materials=dict(sorted(Counter(scene.values()).items())))
    assert metadata['bounds'] == [[-147,1,32],[147,360,118]], metadata['bounds']
    return scene


def compress_count(scene):
    # Exact run compression in all three axes, preserving every color and void.
    counts = {}
    for axis in range(3):
        other = [a for a in range(3) if a != axis]
        groups = {}
        for p,b in scene.items():
            groups.setdefault((p[other[0]],p[other[1]],b),[]).append(p[axis])
        count = 0
        for values in groups.values():
            values.sort()
            count += 1 + sum(b!=a+1 for a,b in zip(values,values[1:]))
        counts['xyz'[axis]] = count
    assert min(counts.values())+5 > 10000
    return counts


def structures(scene, check):
    # Pin the stable codec used by this sculpture; other shared generators may
    # configure their own newer palette version when imported for analysis.
    nbt.BLOCK_VERSION = 17_959_425
    specs = []
    restored = {}
    for xi,x0 in enumerate(range(-147,148,64),1):
        for yi,y0 in enumerate((1,258),1):
            for zi,z0 in enumerate(range(32,119,64),1):
                high = (min(x0+63,147), min(y0+256,360), min(z0+63,118))
                size = tuple(b-a+1 for a,b in zip((x0,y0,z0),high))
                selected = {p:b for p,b in scene.items() if all(a<=v<=h for a,v,h in zip((x0,y0,z0),p,high))}
                if not selected:
                    continue
                palette = sorted(set(selected.values()))
                mapping = {b:i for i,b in enumerate(palette)}
                layer = np.full(size,-1,dtype='<i4')
                for (x,y,z),b in selected.items():
                    layer[x-x0,y-y0,z-z0] = mapping[b]
                volume = int(layer.size)
                layers = (nbt.tag_header(9,'block_indices')+bytes([9])+struct.pack('<i',2)
                          +bytes([3])+struct.pack('<i',volume)+layer.tobytes()
                          +bytes([3])+struct.pack('<i',volume)+np.full(volume,-1,dtype='<i4').tobytes())
                payload = (layers+nbt.tag_compound_list('entities',[])+nbt.tag_compound('palette',
                    nbt.tag_compound('default',nbt.tag_compound_list('block_palette',[nbt.palette_entry(nbt.Block(b)) for b in palette])
                                     +nbt.tag_compound('block_position_data',b''))))
                data = (b'\x0a\x00\x00'+nbt.tag_int('format_version',1)+nbt.tag_int_list('size',list(size))
                        +nbt.tag_compound('structure',payload)+nbt.tag_int_list('structure_world_origin',[0,0,0])+b'\x00')
                name = f'ad2044_x{xi}_y{yi}_z{zi}'
                path = ROOT/'src/structures/ai_minecraft_builds'/f'{name}.mcstructure'
                write(path,data,check)
                root,end = nbt.read_payload(path.read_bytes(),3,10)
                assert end == len(data) and root['size'] == list(size) and root['format_version']==1
                assert root['structure_world_origin']==[0,0,0]
                structure = root['structure']
                assert structure['entities']==[]
                assert structure['palette']['default']['block_position_data']=={}
                entries = structure['palette']['default']['block_palette']
                assert [e['name'] for e in entries]==palette
                assert all(e['states']=={} and e['version']==nbt.BLOCK_VERSION for e in entries)
                first,second = structure['block_indices']
                assert len(first)==len(second)==volume and set(second)=={-1}
                assert all(-1<=i<len(palette) for i in first)
                decoded = {}
                for index,i in enumerate(first):
                    if i==-1:continue
                    x,rem=divmod(index,size[1]*size[2]);y,z=divmod(rem,size[2])
                    decoded[(x+x0,y+y0,z+z0)]=palette[i]
                assert decoded==selected
                assert not restored.keys() & decoded.keys()
                restored.update(decoded)
                # Three checks distributed within each asset, with exact names
                # and positions included in metrics and the engine audit.
                samples = sorted(selected)[::max(1,len(selected)//3)][:3]
                specs.append(dict(name=name,low=[x0,y0,z0],high=list(high),size=list(size),blocks=len(selected),bytes=len(data),
                                  samples=[dict(position=list(p),block=selected[p]) for p in samples]))
    assert restored==scene
    for angle in (0,90,180,270):
        transformed = {}
        for s in specs:
            x0,y0,z0=s['low'];sx,sy,sz=s['size']
            ax=x0+sx-1 if angle in (180,270) else x0
            az=z0+sz-1 if angle in (90,180) else z0
            for p,b in scene.items():
                x,y,z=p
                if not all(l<=v<=h for l,v,h in zip(s['low'],p,s['high'])):continue
                u,v=x-x0,z-z0
                q={0:(ax+u,y,az+v),90:(-az+sz-1-v,y,ax+u),
                   180:(-ax+sx-1-u,y,-az+sz-1-v),270:(az+v,y,-ax+sx-1-u)}[angle]
                assert q not in transformed
                transformed[q]=b
        expected={( {0:(x,z),90:(-z,x),180:(-x,-z),270:(z,-x)}[angle][0],y,
                    {0:(x,z),90:(-z,x),180:(-x,-z),270:(z,-x)}[angle][1]):b for (x,y,z),b in scene.items()}
        assert transformed==expected
    return specs


